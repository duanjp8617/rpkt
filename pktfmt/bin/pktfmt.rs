use std::env;
use std::fs::File;
use std::io::Write;
use std::path::PathBuf;

use pktfmt::{ast, codegen, file_text, parser, token, utils};

// A helper that will write an "error" line to the output channel.
fn preceed_with_error(output: &mut dyn Write) -> &mut dyn Write {
    write!(output, "error: ").unwrap();
    output
}

fn handle_args(args: &Vec<String>) -> Result<(PathBuf, PathBuf, Option<PathBuf>), String> {
    let mut input_path = None;
    let mut output_path = None;
    let mut verus_path = None;

    let help = r#"Usage: pktfmt *.pktfmt [options]
Options:
  -o <file>   Generate the output in <file>.
  --verus <file>  Also emit Verus byte-range proof companions (not FFI proofs).
  -h          Display help information."#;

    let mut i = 1;
    while i < args.len() {
        if (&args[i]).ends_with(".pktfmt") && args[i].len() > ".pktfmt".len() {
            // Find a ".pktfmt" suffix, which should be an input file
            match input_path {
                None => input_path = Some(&args[i]),
                Some(_) => return Err(format!("found another input file {}\n{help}", &args[i])),
            }
            i += 1;
        } else if &args[i] == "-o" && (i + 1 < args.len()) {
            match output_path {
                None => output_path = Some(&args[i + 1]),
                Some(_) => {
                    return Err(format!(
                        "found another output file {}\n{help}",
                        &args[i + 1]
                    ))
                }
            }
            i += 2;
        } else if &args[i] == "--verus" && (i + 1 < args.len()) {
            if verus_path.replace(PathBuf::from(&args[i + 1])).is_some() {
                return Err(format!("duplicate --verus argument\n{help}"));
            }
            i += 2;
        } else if &args[i] == "-h" {
            print!("{help}");
            std::process::exit(0);
        } else {
            return Err(format!("invalid argument {}\n{help}", &args[i]));
        }
    }

    let (input, output) = match (input_path, output_path) {
        (Some(i), Some(o)) => Ok((PathBuf::from(i), PathBuf::from(o))),
        (Some(i), None) => {
            let end_idx = i.rfind(".pktfmt").unwrap();
            let start_idx = match i.rfind("/") {
                Some(i) => i + 1,
                None => 0,
            };
            assert!(start_idx != end_idx);
            let output_file = std::env::current_dir()
                .unwrap()
                .join(format!("{}.rs", &i[start_idx..end_idx]));
            println!(
                "warning: using {} as the output file",
                output_file.display()
            );
            Ok((PathBuf::from(i), output_file))
        }
        _ => Err(format!("missing input arguments\n{help}")),
    }?;
    if verus_path
        .as_ref()
        .is_some_and(|p| p == &input || p == &output)
    {
        return Err("Verus output must differ from input and Rust output".into());
    }
    Ok((input, output, verus_path))
}

// The driver function that runs the code generation pipeline.
fn driver(
    file_text: &file_text::FileText,
    output_file: &PathBuf,
    verus_file: Option<&PathBuf>,
) -> Result<(), utils::Error> {
    // Parse for the top level ast.
    let tokenizer = token::Tokenizer::new(file_text.text());
    let (start_code, parsed_items) = parser::TopLevelParser::new()
        .parse(
            tokenizer
                .into_iter()
                .map(|tk_res| tk_res.map_err(|err| utils::Error::Token(err))),
        )
        .map_err(|err| match err {
            lalrpop_util::ParseError::User { error } => error,
            _ => utils::Error::Lalrpop(format!("{err}")),
        })?;
    let top_level = ast::TopLevel::new(&parsed_items[..])
        .map_err(|(err, span)| utils::Error::Ast { err, span })?;

    // Prepare the output channel.
    let mut output_f = File::create(output_file)
        .map_err(|err| utils::Error::ErrStr(format!("{}: {err}", output_file.to_str().unwrap())))?;
    let mut proof_f = verus_file
        .map(File::create)
        .transpose()
        .map_err(|err| utils::Error::ErrStr(format!("Verus output: {err}")))?;
    if let Some(out) = &mut proof_f {
        writeln!(out, "// Generated by pktfmt --verus; see verification/README.md.\n#![allow(non_snake_case, unused_imports)]")
            .map_err(|e| utils::Error::ErrStr(e.to_string()))?;
    }

    // Do the code generation.
    write!(&mut output_f, "{start_code}").unwrap();
    writeln!(&mut output_f, "").unwrap();
    for (parsed_item, code_opt) in top_level.item_iter() {
        match parsed_item {
            ast::ParsedItem::Packet_(p) => {
                let header = codegen::HeaderGen::new(p);
                header.code_gen(&mut output_f);
                writeln!(&mut output_f, "").unwrap();
                let packet = codegen::PktGen::new(&header);
                let mut rust = Vec::new();
                packet.code_gen(&mut rust);
                output_f.write_all(&rust).unwrap();
                if let Some(out) = &mut proof_f {
                    codegen::verus::check_packet_parse_gates(
                        std::str::from_utf8(&rust).unwrap(),
                        p.header().header_len_in_bytes(),
                    )
                    .map_err(utils::Error::ErrStr)?;
                    codegen::verus::generate(
                        p.protocol_name(),
                        p.header().header_len_in_bytes(),
                        std::str::from_utf8(&rust).unwrap(),
                        out,
                    )
                    .map_err(utils::Error::ErrStr)?;
                }
            }
            ast::ParsedItem::PacketGroup_(mg) => {
                let defined_name = mg.name();
                let (msgs, cond_fields, iter_gen) = top_level.pkt_group(defined_name).unwrap();
                let message_group =
                    codegen::PacketGroupGen::new(defined_name, msgs, cond_fields, iter_gen);
                let mut rust = Vec::new();
                message_group.code_gen(&mut rust);
                output_f.write_all(&rust).unwrap();
                if let Some(out) = &mut proof_f {
                    let minimum = cond_fields
                        .iter()
                        .map(|(pos, field)| pos.next_pos(field.bit).byte_pos() as usize + 1)
                        .max()
                        .unwrap();
                    codegen::verus::generate(
                        defined_name,
                        minimum,
                        std::str::from_utf8(&rust).unwrap(),
                        out,
                    )
                    .map_err(utils::Error::ErrStr)?;
                }
            }
        }
        writeln!(&mut output_f, "").unwrap();
        code_opt.as_ref().map(|code| {
            writeln!(&mut output_f, "{code}").unwrap();
            writeln!(&mut output_f, "").unwrap();
        });
    }

    Ok(())
}

fn main() {
    let args: Vec<String> = env::args().into_iter().collect();
    let mut stderr = std::io::stderr();

    // Handle the input args
    let (input_file, output_file, verus_file) = match handle_args(&args) {
        Ok(res) => res,
        Err(err_str) => {
            writeln!(preceed_with_error(&mut stderr), "{err_str}").unwrap();
            std::process::exit(1);
        }
    };

    // Prepare the file text.
    let file_text = match file_text::FileText::new(input_file) {
        Ok(file_text) => file_text,
        Err(e) => {
            writeln!(preceed_with_error(&mut stderr), "{e}").unwrap();
            std::process::exit(1);
        }
    };

    // Run the code generation driver.
    match driver(&file_text, &output_file, verus_file.as_ref()) {
        Err(err) => {
            utils::render_error(&file_text, err, &mut stderr);
            std::process::exit(1)
        }
        Ok(_) => {}
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn args(words: &[&str]) -> Vec<String> {
        words.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn verus_companion_is_opt_in_and_has_a_separate_output() {
        let plain = handle_args(&args(&["pktfmt", "p.pktfmt", "-o", "p.rs"])).unwrap();
        assert!(plain.2.is_none());
        let paired = handle_args(&args(&[
            "pktfmt",
            "p.pktfmt",
            "-o",
            "p.rs",
            "--verus",
            "p_proof.rs",
        ]))
        .unwrap();
        assert_eq!(paired.2, Some(PathBuf::from("p_proof.rs")));
        assert!(handle_args(&args(&[
            "pktfmt", "p.pktfmt", "-o", "p.rs", "--verus", "p.rs"
        ]))
        .is_err());
        assert!(handle_args(&args(&["pktfmt", "p.pktfmt", "-o", "p.rs", "--verus"])).is_err());
    }
}
